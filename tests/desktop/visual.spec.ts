const classTokens = (classAttribute: string | null): string[] =>
  (classAttribute ?? '').split(/\s+/).filter(Boolean);

/** Exactly one reference theme token may be active on a surface. */
function hasOnlyToken(
  classAttribute: string | null,
  expected: string,
  known: readonly string[],
  companions: readonly string[] = [],
): boolean {
  const observed = classTokens(classAttribute);
  return (
    observed.includes(expected) &&
    known.every(
      (token) =>
        token === expected ||
        companions.includes(token) ||
        !observed.includes(token),
    )
  );
}

