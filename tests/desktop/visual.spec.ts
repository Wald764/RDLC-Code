/**
 * Feature 005 US6 (AT-08): theme pixel references and composited contrast on a
 * real Desktop.
 *
 * Every test title is the executable assertion ID registered in coverage.json
 * (`tests/desktop/visual.spec.ts::<title>`).
 *
 * The runner guards the reference environment only for `--probe`, so every
 * test here proves the reference itself from the actual driver observations
 * (`environmentFromDriver` over the live identity, `/etc/os-release` and
 * `fc-list`) and against the recorded reference metadata before a single
 * screenshot can count. Contrast is measured from composited screenshot pixels,
 * never from CSS token guesses: the surface is the dominant colour actually
 * painted in the measured box and the foreground only counts when an observed
 * cluster carries the element's own computed colour composited through its
 * ancestor opacities, so a high-contrast decoy can never stand in for
 * low-contrast text. An essential icon is measured the same way, and only
 * against a glyph paint proven from computed style (a native mask background,
 * a resolved SVG fill/stroke or font glyph colour): when that paint cannot be
 * proven the measurement stays unvalidated with its reason, and the farthest
 * colour is recorded as a supplementary diagnostic that never satisfies a
 * requirement. No baseline, metadata or fingerprint is generated by this
 * file: a missing reference fails closed. The maths lives in
 * `visual-contrast.ts` and is checked by `visual-contrast.test.ts`.
 *
 * Open diagnostic, not a claim of complete coverage: contrast here is
 * measured only at the pinned 100% reference scale recorded in the reference
 * metadata. The 200% variants of FR-028/US6.2 are absent from this file and
 * are recorded as open in the contrast artefacts; the interface scale protocol
 * belongs to `layout.spec.ts`, and running it here would report contrast at a
 * scale the recorded reference identity does not describe.
 */
