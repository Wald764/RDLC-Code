/**
 * Fail before any pixel evidence counts: the observed driver environment must
 * be the pinned reference, and the recorded reference must describe this same
 * environment, font set, binary and comparison budget.
 */
async function assertReferenceEnvironment(ctx: Ctx): Promise<void> {
  const { environment } = ctx;
  expect(
    referenceEnvironmentReasons(environment),
    'the actual observed driver environment must match the pinned reference',
  ).toEqual([]);
  expect(
    environment.fonts,
    'the live font read (fc-list) must return the installed families',
  ).not.toBe('');
  expect(
    environment.vscodeHash,
    'the launched binary must be identified',
  ).toMatch(/^[0-9a-f]{64}$/);

  const root = process.env.RDLC_DESKTOP_ROOT ?? process.cwd();
  const file = resolve(root, REFERENCE_METADATA);
  expect(
    existsSync(file),
    `reference metadata ${REFERENCE_METADATA} is missing; it must be generated on the pinned reference image before any visual comparison counts`,
  ).toBe(true);
  const recorded = JSON.parse(await readFile(file, 'utf8')) as {
    environment?: EnvironmentIdentity;
    vscode?: { executableSha256?: string };
    tolerances?: { threshold?: number; maxDiffPixelRatio?: number };
  };
  const observed = recorded.environment;
  expect(
    observed,
    'the reference metadata records an environment',
  ).toBeDefined();
  for (const [name, actual, wanted] of [
    ['os', environment.os, observed!.os],
    ['osImage', environment.osImage, observed!.osImage],
    ['vscodeVersion', environment.vscodeVersion, observed!.vscodeVersion],
    ['vscodeBuild', environment.vscodeBuild, observed!.vscodeBuild],
    ['locale', environment.locale, observed!.locale],
    ['timezone', environment.timezone, observed!.timezone],
    ['fonts', environment.fonts, observed!.fonts],
    ['display.width', environment.display.width, observed!.display.width],
    ['display.height', environment.display.height, observed!.display.height],
    ['display.dpr', environment.display.dpr, observed!.display.dpr],
  ] as const)
    expect(actual, `reference metadata ${name}`).toBe(wanted);
  expect(recorded.vscode?.executableSha256).toBe(environment.vscodeHash);
  expect(
    recorded.tolerances,
    'the recorded comparison budget must not be softened',
  ).toEqual({ ...TOLERANCES });
}

/**
 * Reference baselines must exist before a comparison can pass. This gate never
 * writes them; only an explicit reference-generation run (the runner's
 * RDLC_DESKTOP_UPDATE_BASELINES plus Playwright --update-snapshots=all, refused
 * in CI without RDLC_ALLOW_CI_BASELINE_UPDATE=1) skips it so they can be created.
 */
function requireBaselines(paths: readonly string[]): void {
  if (process.env.RDLC_DESKTOP_UPDATE_BASELINES === 'true') return;
  const root = process.env.RDLC_DESKTOP_ROOT ?? process.cwd();
  const missing = paths.filter(
    (path) => !existsSync(resolve(root, BASELINE_ROOT, path)),
  );
  expect(
    missing,
    'reference baselines are missing; generate them on the pinned reference image with --update-baselines (this suite never writes them)',
  ).toEqual([]);
}

