/** Capture a region in CSS pixels so boxes and pixels share one coordinate space. */
async function capture(
  container: Locator,
  target?: Locator,
): Promise<{ image: Image; rect: Rect }> {
  const box = await container.boundingBox();
  if (!box) throw new Error('The captured region has no bounds');
  const image = decodePng(await container.screenshot({ scale: 'css' }));
  if (!target)
    return {
      image,
      rect: { x: 0, y: 0, width: box.width, height: box.height },
    };
  const inner = await target.boundingBox();
  if (!inner) throw new Error('The measured element has no bounds');
  return {
    image,
    rect: {
      x: inner.x - box.x,
      y: inner.y - box.y,
      width: inner.width,
      height: inner.height,
    },
  };
}

/** Innermost rendered element that carries the visible text of a container. */
const textLeaf = (root: Locator): Locator =>
  root
