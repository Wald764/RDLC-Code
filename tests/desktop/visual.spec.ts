test('FR-028-contrast', async () => {
  await session(
    { 'contrast.rdlc': { fixture: 'textbox-supported' } },
    async (ctx) => {
      const { page } = ctx;
      const source = await readFile(ctx.path('contrast.rdlc'));
      await assertReferenceEnvironment(ctx);
      await palette(page, 'View: Show RDLC Code');
      await openReport(ctx, 'contrast.rdlc');
      const frame = await openDesigner(ctx);
      test.info().annotations.push({
        type: 'open-diagnostic',
        description: OPEN_SCALE_DIAGNOSTIC,
      });

      const sidebar = page.locator('.part.sidebar');
      const structure = structurePane(page).first();
      const header = structure.locator('.pane-header');
      const row = structure.getByRole('treeitem').first();
      const activity = page.locator('.activitybar').getByRole('tab', {
        name: /^RDLC Code/,
      });
      await expect(structure, 'the report structure pane').toBeVisible();
      await expect(header).toContainText('Report Structure');
      await expect(row).toBeVisible();
      await expect(activity).toHaveCount(1);

      const measured: Record<
        string,
        Record<string, Measurement & { readonly minimum: number }>
      > = {};
      const results: Record<string, ContrastResult[]> = {};
      const glyphs: Record<string, { source: string; reason: string | null }> =
        {};
      for (const theme of THEMES) {
        await applyTheme(page, frame, theme);
        // The glyph paint is a theme token (the selected activity item uses
        // its own foreground), so it is proven again for every theme, after
        // the theme is live, never carried over from the startup theme.
        const glyph = await paintedGlyph(activity);
        glyphs[theme.label] = { source: glyph.source, reason: glyph.reason };
        test.info().annotations.push({
          type: glyph.reason ? 'unvalidated-glyph-paint' : 'glyph-paint-source',
          description: glyph.reason
            ? `${theme.label}: the activity icon paint is unvalidated: ${glyph.reason}`
            : `${theme.label}: the activity icon is painted by ${glyph.source}`,
        });
        const labelLeaf = textLeaf(row);
        const titleLeaf = textLeaf(header);
        const icon = await capture(page.locator('.activitybar'), activity);
        const label = await capture(sidebar, labelLeaf);
        const title = await capture(header, titleLeaf);
        const labelPaint = await paintedText(labelLeaf);
        const titlePaint = await paintedText(titleLeaf);
        const entry: Record<
          string,
          Measurement & { readonly minimum: number }
        > = {
          // Only a paint proven by computed style can measure this icon; the
          // farthest colour is a diagnostic and never an acceptance condition.
          'activity icon': {
            ...glyphContrast(icon.image, icon.rect, glyph),
            minimum: MIN_BOUNDARY_RATIO,
          },
          'tree label': {
            ...textContrast(label.image, label.rect, labelPaint),
            minimum: MIN_TEXT_RATIO,
          },
          'view title': {
            ...textContrast(title.image, title.rect, titlePaint),
            minimum: MIN_TEXT_RATIO,
          },
        };
        measured[theme.label] = entry;
        results[theme.label] = Object.entries(entry).map(([region, value]) =>
          contrastResult(region, value),
        );
      }

      expect(
        (await readFile(ctx.path('contrast.rdlc'))).equals(source),
        'contrast work never edits the report',
      ).toBe(true);
      // Evidence is written before any threshold can fail the run, so an
      // unvalidated glyph still records its reason instead of disappearing.
      await writeRecord(ctx, 'visual-contrast.json', {
        assertion: 'tests/desktop/visual.spec.ts::FR-028-contrast',
        environment: ctx.environment,
        method:
          "composited screenshot pixels: the surface is the dominant colour painted in the box, and the foreground counts only when an observed cluster within the channel tolerance carries the element's own computed colour composited through its ancestor opacities over that surface; the farthest colour is recorded as a supplementary diagnostic and never satisfies a requirement",
        glyphs,
        scaleScope: OPEN_SCALE_DIAGNOSTIC,
        results,
      });
      for (const [theme, entries] of Object.entries(measured))
        for (const [region, value] of Object.entries(entries))
          await expectContrast(`${theme} ${region}`, value, value.minimum);
      await ctx.driver.capture('fr-028-contrast');
    },
  );
});

test('SC-006-contrast', async () => {
  await session(
    { 'contrast.rdlc': { fixture: 'textbox-supported' } },
    async (ctx) => {
      const { page } = ctx;
      const source = await readFile(ctx.path('contrast.rdlc'));
      await assertReferenceEnvironment(ctx);
      // With the secondary side bar open the designer is only ~750 px wide:
      // the flexible status text collapses to zero width and the inspector
      // becomes an overlay. Hide the bar for this test only so the footer has
      // room; the shared session defaults (and their references) stay as is.
      const auxiliaryBar = page.locator('.part.auxiliarybar');
      if (await auxiliaryBar.isVisible())
        await palette(page, 'View: Hide Secondary Side Bar');
      await expect(auxiliaryBar).toBeHidden();
      await palette(page, 'View: Show RDLC Code');
      await openReport(ctx, 'contrast.rdlc');
      const frame = await openDesigner(ctx);
      await frame.locator('.item[data-item="0"]').click();
      await expect(frame.locator('.item.primary')).toHaveCount(1);
      // The status footer only spans the canvas column, which the inline
      // inspector narrows; without the primary side bar the text has room.
      await palette(page, 'View: Close Primary Side Bar', frame);
      await expect(page.locator('.part.sidebar')).toBeHidden();
      // The inspector (geometry note and properties form) is inline from
      // 800 px of workspace width (aria-expanded already "true") and a hidden
      // overlay below it, so it is opened only when it is not yet shown.
      const properties = frame.getByRole('button', {
        name: 'Properties',
        exact: true,
      });
      if ((await properties.getAttribute('aria-expanded')) === 'false')
        await properties.click();
      await expect(properties).toHaveAttribute('aria-expanded', 'true');
      await expect(
        frame.locator('p[aria-label="Accepted item geometry"]'),
      ).toBeVisible();
      await expect(
        frame.locator('form[aria-label="Textbox properties"]'),
      ).toBeVisible();

      const results: Record<string, ContrastResult[]> = {};
      for (const theme of THEMES) {
        await applyTheme(page, frame, theme);
        const status = frame.locator('.status-text');
        const selection = frame.locator('.selection-frame');
        const inspectorLabel = frame
          .locator('form[aria-label="Textbox properties"] label.field span')
          .first();
        const body = frame.locator('.body');
        const inspector = frame.locator(
          'form[aria-label="Textbox properties"]',
        );
        await expect(status).toBeVisible();
        expect(
          (await status.boundingBox())?.width ?? 0,
          `${theme.label} status text keeps a non-zero width`,
        ).toBeGreaterThan(0);
        await expect(selection).toHaveCount(1);
        await expect(inspectorLabel).toBeVisible();

        const statusCapture = await capture(status);
        const selectionCapture = await capture(body, selection);
        const inspectorCapture = await capture(inspector, inspectorLabel);
        const statusPaint = await paintedText(status);
        const edges = await paintedEdges(selection);
        const inspectorPaint = await paintedText(inspectorLabel);
        const measured = {
          'status text': {
            ...textContrast(
              statusCapture.image,
              statusCapture.rect,
              statusPaint,
            ),
            minimum: MIN_TEXT_RATIO,
          },
          'selection boundary': {
            ...boundaryContrast(
              selectionCapture.image,
              selectionCapture.rect,
              edges,
            ),
            minimum: MIN_BOUNDARY_RATIO,
          },
          'inspector label': {
            ...textContrast(
              inspectorCapture.image,
              inspectorCapture.rect,
              inspectorPaint,
            ),
            minimum: MIN_TEXT_RATIO,
          },
        };
        results[theme.label] = Object.entries(measured).map(([region, value]) =>
          contrastResult(region, value),
        );
        for (const [region, value] of Object.entries(measured))
          await expectContrast(
            `${theme.label} ${region}`,
            value,
            value.minimum,
          );
      }

      // The success criterion is the whole matrix passing, recorded per theme.
      const failures = Object.entries(results).flatMap(([theme, entries]) =>
        entries
          .filter((entry) => !entry.matched || entry.ratio < entry.minimum)
          .map(
            (entry) =>
              `${theme} ${entry.region} ${
                entry.matched
                  ? `${entry.ratio}:1`
                  : 'no matching painted foreground'
              }`,
          ),
      );
      expect(
        failures,
        'every reference theme passes every contrast oracle',
      ).toEqual([]);
      expect(
        (await readFile(ctx.path('contrast.rdlc'))).equals(source),
        'contrast work never edits the report',
      ).toBe(true);
      await writeRecord(ctx, 'visual-contrast-sc-006.json', {
        assertion: 'tests/desktop/visual.spec.ts::SC-006-contrast',
        environment: ctx.environment,
        results,
      });
      await ctx.driver.capture('sc-006-contrast');
    },
  );
});
