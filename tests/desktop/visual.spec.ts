/** The pane that really holds the report structure, never the first sidebar pane. */
const structurePane = (page: Page): Locator =>
  page.locator('.part.sidebar .pane').filter({
    has: page.locator('.pane-header', { hasText: 'Report Structure' }),
  });

/** Apply a bundled theme through the real quick pick and prove both surfaces. */
async function applyTheme(
  page: Page,
  frame: Frame,
  theme: Theme,
): Promise<{ workbench: string; webview: string }> {
  await palette(page, 'Preferences: Color Theme', frame);
  const input = page.locator(
    '.quick-input-widget:visible .quick-input-box input',
  );
  await input.waitFor({ state: 'visible' });
  await page.keyboard.type(theme.label, { delay: 10 });
  // The first row can be "Browse Additional Color Themes..." (recently used).
  const row = exactLabelRow(page, theme.label);
  await expect(row, `theme row for ${theme.label}`).toBeVisible();
  await row.click();
  await expect(page.locator('.quick-input-widget:visible')).toBeHidden();
  const workbenchClass = async (): Promise<string> =>
    (await page.locator('.monaco-workbench').getAttribute('class')) ?? '';
  const webviewClass = async (): Promise<string> =>
    (await frame.locator('body').getAttribute('class')) ?? '';
  // Exact token membership: `vs` and `hc-light` must be proved as themselves,
  // never as a substring of the token another theme owns.
  await expect
    .poll(
      () =>
        workbenchClass().then((value) =>
          hasOnlyToken(value, theme.workbench, WORKBENCH_THEMES),
        ),
      {
        message: `exactly the ${theme.label} workbench token is active`,
      },
    )
    .toBe(true);
  await expect
    .poll(
      () =>
        webviewClass().then((value) =>
          hasOnlyToken(
            value,
            theme.webview,
            WEBVIEW_THEMES,
            theme.webviewCompanions,
          ),
        ),
      {
        message: `exactly the ${theme.label} webview token is active`,
      },
    )
    .toBe(true);
  await page.waitForTimeout(500);
  return {
    workbench: await workbenchClass(),
    webview: await webviewClass(),
  };
}

async function writeRecord(
  ctx: Ctx,
  name: string,
  record: Record<string, unknown>,
): Promise<void> {
  await writeFile(
    join(ctx.artifacts, name),
    `${JSON.stringify({ schemaVersion: 1, ...record }, null, 2)}\n`,
  );
}

